import fs from "node:fs";
import ts from "typescript";

// Reviewed database-only modules. Auth provisioning, sending messages, backups,
// file imports, and quick-add helpers which need real IDs stay server-confirmed.
const modules = ["accounts", "brands", "categories", "companies", "contacts", "expenses", "inter-company", "ledger", "locations", "market-purchases", "payments", "products", "purchases", "quotations", "returns", "roles", "sales", "settings", "stock-adjustments", "stock-transfers", "taxes", "transfers", "unit-conversions", "units"];
const registry = [];
const reads = [];
fs.mkdirSync("lib/client-actions", { recursive: true });
for (const domain of modules) {
  const source = fs.readFileSync(`lib/actions/${domain}.ts`, "utf8");
  const ast = ts.createSourceFile(domain, source, ts.ScriptTarget.Latest, true);
  const names = ast.statements.filter(n => ts.isFunctionDeclaration(n) && n.modifiers?.some(m => m.kind === ts.SyntaxKind.ExportKeyword)).map(n => n.name.text);
  const writes = names.filter(name => /^(create|update|delete|save|merge|assign|approve|confirm|cancel|convert|set)[A-Z]/.test(name));
  const getters = names.filter(name => /^(get|list)[A-Z]/.test(name));
  const alias = domain.replaceAll("-", "_");
  registry.push(`import * as ${alias} from "@/lib/actions/${domain}";`);
  const code = [`"use client";`, `// Generated by scripts/generate-background-actions.mjs.`, `import * as server from "@/lib/actions/${domain}";`, `import { backgroundAction, backgroundRead } from "@/lib/background-client";`, `export type * from "@/lib/actions/${domain}";`];
  for (const name of names) {
    if (writes.includes(name)) code.push(`export const ${name}: typeof server.${name} = backgroundAction("${domain}.${name}", server.${name});`);
    else if (getters.includes(name)) code.push(`export const ${name}: typeof server.${name} = backgroundRead("${domain}.${name}", server.${name});`);
    else code.push(`export const ${name} = server.${name};`);
  }
  fs.writeFileSync(`lib/client-actions/${domain}.ts`, code.join("\n") + "\n");
  reads.push({ domain, alias, writes, getters });
}
registry.push("", "export const commandActions = {");
for (const { domain, alias, writes } of reads) for (const name of writes) registry.push(`  "${domain}.${name}": ${alias}.${name},`);
registry.push("} as const;", "", "export const commandReads = {");
for (const { domain, alias, getters } of reads) for (const name of getters) registry.push(`  "${domain}.${name}": ${alias}.${name},`);
registry.push("} as const;", "");
fs.writeFileSync("lib/command-registry.ts", 'import "server-only";\n// Explicit allowlist generated by scripts/generate-background-actions.mjs.\n' + registry.join("\n"));

function walk(dir) {
  for (const item of fs.readdirSync(dir, { withFileTypes: true })) {
    const path = `${dir}/${item.name}`;
    if (item.isDirectory()) walk(path);
    else if (/\.tsx?$/.test(path) && !path.endsWith("quick-add.ts")) {
      let code = fs.readFileSync(path, "utf8");
      const original = code;
      if (!code.includes('"use client"')) continue;
      // The legacy sync provider submits actual actions; never make it enqueue itself.
      if (path.endsWith("SyncProvider.tsx")) continue;
      for (const domain of modules) code = code.replaceAll(`from "@/lib/actions/${domain}"`, `from "@/lib/client-actions/${domain}"`);
      if (code !== original) fs.writeFileSync(path, code);
    }
  }
}
walk("components");
